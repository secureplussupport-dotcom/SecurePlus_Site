// Builds src/data/readinessConceptCatalogue.js from the active MCQ bank.
//
// A concept tag belongs to a domain when at least one base-catalogue question
// in that domain uses it as its primary tag. A tag tested in several domains
// therefore appears in each of those domains: readiness averages the concepts
// a domain actually tests, it does not invent a single-domain mapping for a
// tag. Tags with no base-catalogue question have no domain and are not in
// the catalogue; if a learner later attempts one, examReadiness.js adds it
// to the domain of that attempt instead of silently dropping it.
//
// Usage: node scripts/build-readiness-catalogue.mjs [--check]
// --check exits non-zero when the checked-in catalogue differs, so a bank
// change cannot silently leave readiness using a stale catalogue.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const outPath = path.join(root, 'src/data/readinessConceptCatalogue.js');

export function buildReadinessCatalogue() {
  const base = JSON.parse(readFileSync(path.join(root, 'server/mcq-engine/base-catalogue.json'), 'utf8'));
  const assignments = JSON.parse(readFileSync(path.join(root, 'src/data/mcqConceptTagAssignments.json'), 'utf8'));
  const chapterByQuestion = new Map(base.map((q) => [q.id, String(q.ch)]));
  const byDomain = { 1: new Set(), 2: new Set(), 3: new Set(), 4: new Set(), 5: new Set() };
  for (const row of assignments.assignments || []) {
    const domain = chapterByQuestion.get(row.questionId);
    if (byDomain[domain] && row.primaryTagId) byDomain[domain].add(row.primaryTagId);
  }
  return Object.fromEntries(
    Object.entries(byDomain).map(([domain, tags]) => [domain, [...tags].sort()]),
  );
}

function render(catalogue) {
  const pairs = Object.values(catalogue).reduce((sum, tags) => sum + tags.length, 0);
  const lines = [
    '// Generated by scripts/build-readiness-catalogue.mjs — do not edit by hand.',
    '// A tag appears in every domain where a base-catalogue question uses it as',
    `// its primary tag (${pairs} tag-domain pairs, from the active MCQ bank).`,
    '// Unattempted tags count as 50 in examReadiness.js; see that file for the',
    '// full readiness formula and confidence rules.',
    '',
    'export const READINESS_CONCEPT_CATALOGUE = Object.freeze({',
    ...Object.entries(catalogue).map(
      ([domain, tags]) => `  '${domain}': Object.freeze([${tags.map((tag) => `'${tag}'`).join(', ')}]),`,
    ),
    '});',
    '',
  ];
  return lines.join('\n');
}

const catalogue = buildReadinessCatalogue();
const rendered = render(catalogue);
if (process.argv.includes('--check')) {
  const current = readFileSync(outPath, 'utf8');
  if (current !== rendered) {
    console.error('Readiness catalogue is stale. Run: node scripts/build-readiness-catalogue.mjs');
    process.exit(1);
  }
  console.log('Readiness catalogue is up to date.');
} else {
  writeFileSync(outPath, rendered);
  const total = Object.values(catalogue).reduce((sum, tags) => sum + tags.length, 0);
  console.log(`Wrote ${outPath} (${total} tag-domain pairs).`);
}
