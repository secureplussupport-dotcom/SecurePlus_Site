const makeCard = (setId, entry, defaultTopic = "") => {
  const [acronym, expansion, meaning, extra = {}, explicitTopic = ""] = entry;
  const metadata = typeof extra === "object" && extra !== null ? extra : {};
  const topic = explicitTopic || metadata.topic || (typeof extra === "string" ? extra : "") || defaultTopic;
  return {
    id: `sy0701-acronym-${setId}-${slug(`${acronym}-${expansion}`)}`,
    acronym,
    expansion,
    meaning,
    topic,
    ...(metadata.example ? { example: metadata.example } : {}),
    ...(metadata.cardType ? { cardType: metadata.cardType } : {}),
  };
};

const makeTermCard = (setId, entry, defaultTopic = "") => {
  const [term, meaning, extra = {}, explicitTopic = ""] = entry;
  const metadata = typeof extra === "object" && extra !== null ? extra : {};
  const topic = explicitTopic || metadata.topic || (typeof extra === "string" ? extra : "") || defaultTopic;
  return {
    id: `sy0701-term-${setId}-${slug(term)}`,
    acronym: term,
    expansion: term,
    meaning,
    topic,
    cardType: "term",
  };
};

