export const getSy0701DeepDiveProfile = diveOrId => {
  const id = typeof diveOrId === "string" ? diveOrId : diveOrId?.id;
  const mapped = SY0701_DEEP_DIVE_PROFILES[id];
  if (!mapped) return null;
  const domainId = Number(mapped.objectiveCodes[0].split(".")[0]);
  return {
    ...mapped,
    domainId,
    domain: SY0701_DOMAINS.find(item => item.id === domainId),
    objectiveLabels: mapped.objectiveCodes.map(code => ({ code, title: SY0701_OBJECTIVES[code] })),
    keywordGuide: mapped.examKeywords.map(term => ({ term, meaning: SY0701_KEYWORD_DEFINITIONS[term] })),
    includesBeyondTextbook: mapped.beyondSections.length > 0,
  };
};

export const sortDeepDivesBySy0701 = dives => [...dives].sort((left, right) => {
  const leftProfile = getSy0701DeepDiveProfile(left);
  const rightProfile = getSy0701DeepDiveProfile(right);
  return (leftProfile?.studyOrder || 999) - (rightProfile?.studyOrder || 999);
});
